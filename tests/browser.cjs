    data = await page.evaluate(() => JSON.parse(localStorage.getItem('hanamaru-fuda-v2')));
    assert.equal(data.tasks.filter(t => t.monthlyScheduleId).length, 4);
    assert.equal(data.tasks.some(t => t.occurrenceMonth === '2026-12'), false);
